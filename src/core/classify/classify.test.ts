import { describe, expect, it } from 'vitest';
import { mkFile } from '../group/files.testutil.js';
import { classifyFile, classifyFiles, classifyPath, isMechanical, pairTests } from './index.js';
import { isCommentOnly, isWhitespaceOnly } from './hunk.js';

describe('classifyPath', () => {
  const cases: [string, string[]][] = [
    ['package-lock.json', ['lockfile']],
    ['pnpm-lock.yaml', ['lockfile']],
    ['go.sum', ['lockfile']],
    ['dist/app.js', ['generated']],
    ['api/user.pb.go', ['generated']],
    ['static/app.min.js', ['generated']],
    ['src/__snapshots__/a.test.ts.snap', ['snapshot', 'test']],
    ['vendor/lib/x.go', ['vendor']],
    ['src/foo.test.ts', ['test']],
    ['tests/test_x.py', ['test']],
    ['README.md', ['docs']],
    ['docs/guide.txt', ['docs']],
    ['tsconfig.json', ['config']],
    ['.github/workflows/ci.yml', ['ci', 'config']],
    ['db/migrations/001_init.sql', ['migration']],
    ['package.json', ['deps', 'config']],
    ['requirements-dev.txt', ['deps']],
  ];
  it.each(cases)('%s', (path, expected) => {
    expect(classifyPath(path).sort()).toEqual([...expected].sort());
  });

  it('leaves plain source untagged', () => {
    expect(classifyPath('src/app.ts')).toEqual([]);
  });
});

describe('hunk tags', () => {
  describe('isWhitespaceOnly', () => {
    const ws = (path: string, rows: string[]) => isWhitespaceOnly(mkFile(path, rows).hunks[0]!);
    it('rejects whitespace removed inside a string literal', () => {
      expect(ws('a.ts', ['-const r = "admin user";', '+const r = "adminuser";'])).toBe(false);
    });
    it('rejects Python re-indentation', () => {
      expect(ws('a.py', ['-    run()', '+        run()'])).toBe(false);
    });
    it('accepts JS re-indentation', () => {
      expect(ws('a.ts', ['-    run();', '+        run();'])).toBe(true);
    });
    it('treats unknown extensions as indentation sensitive', () => {
      expect(ws('a.weird', ['-  x', '+    x'])).toBe(false);
      expect(ws('Makefile', ['-\tx', '+  x'])).toBe(false);
    });
    it('accepts trailing-whitespace-only changes, even in Python', () => {
      expect(ws('a.py', ['-run()', '+run()  '])).toBe(true);
    });
    it('accepts blank-line-only changes', () => {
      expect(ws('a.py', ['+', ' x', '-'])).toBe(true);
    });
    it('rejects re-wrapped lines', () => {
      expect(ws('a.ts', ['-  foo( a, b )', '+foo(a,', '+  b)'])).toBe(false);
      expect(ws('a.ts', ['-foo(a, b)', '+foo(a,', '+  b)'])).toBe(false);
    });
    it('rejects real edits', () => {
      expect(ws('a.ts', ['-foo(a)', '+foo(b)'])).toBe(false);
    });
  });

  it('detects comment-only changes per language', () => {
    expect(isCommentOnly(mkFile('a.ts', ['-// old', '+// new', ' code']).hunks[0]!)).toBe(true);
    expect(isCommentOnly(mkFile('a.ts', ['+/**', '+ * doc', '+ */', '+']).hunks[0]!)).toBe(true);
    expect(isCommentOnly(mkFile('a.py', ['+# note']).hunks[0]!)).toBe(true);
    expect(isCommentOnly(mkFile('a.ts', ['+// note', '+run();']).hunks[0]!)).toBe(false);
    expect(isCommentOnly(mkFile('a.json', ['+// x']).hunks[0]!)).toBe(false);
    expect(isCommentOnly(mkFile('a.c', ['+#include <x.h>']).hunks[0]!)).toBe(false);
  });

  it('flags generated files by header marker', () => {
    const f = mkFile('src/schema.ts', ['+// @generated by tool', '+export const x = 1;'], {
      start: 1,
    });
    expect(classifyFile(f)).toContain('generated');
    const g = mkFile('src/schema.ts', ['+// DO NOT EDIT', '+x'], { start: 1 });
    expect(classifyFile(g)).toContain('generated');
    const h = mkFile('src/schema.ts', ['+// ordinary', '+x'], { start: 1 });
    expect(classifyFile(h)).not.toContain('generated');
  });

  it('tags pure renames', () => {
    const f = {
      ...mkFile('b.ts', ['+x'], { status: 'renamed', previous: 'a.ts' }),
      hunks: [],
      additions: 0,
      deletions: 0,
    };
    expect(classifyFile(f)).toContain('rename-only');
  });

  it('marks mechanical hunks', () => {
    const hunks = classifyFiles([
      mkFile('package-lock.json', ['+x']),
      mkFile('src/a.ts', ['+x']),
      mkFile('src/b.ts', ['-a b  ', '+a b']),
      mkFile('src/c.ts', ['+// c']),
    ]);
    expect(hunks.map((h) => h.mechanical)).toEqual([true, false, false, false]);
    expect(hunks[2]!.tags).toContain('whitespace-only'); // tagged, but not mechanical
    expect(hunks[3]!.tags).toContain('comment-only');
    expect(isMechanical(['docs'])).toBe(false);
    expect(isMechanical(['snapshot'])).toBe(true);
  });
});

describe('pairTests', () => {
  it('pairs by naming convention', () => {
    const pairs = pairTests([
      'src/foo.ts',
      'src/foo.test.ts',
      'src/bar.tsx',
      'src/__tests__/bar.tsx',
      'pkg/x.py',
      'pkg/test_x.py',
      'pkg/y.py',
      'pkg/y_test.py',
      'cmd/z.go',
      'cmd/z_test.go',
      'src/lonely.spec.ts',
    ]);
    expect(Object.fromEntries(pairs)).toEqual({
      'src/foo.test.ts': 'src/foo.ts',
      'src/__tests__/bar.tsx': 'src/bar.tsx',
      'pkg/test_x.py': 'pkg/x.py',
      'pkg/y_test.py': 'pkg/y.py',
      'cmd/z_test.go': 'cmd/z.go',
    });
  });

  it('prefers the same directory when stems collide', () => {
    const pairs = pairTests(['a/index.ts', 'b/index.ts', 'b/index.test.ts']);
    expect(pairs.get('b/index.test.ts')).toBe('b/index.ts');
  });
});
