import type { ParsedFile } from '../diff/types.js';
import type { Tag } from './tags.js';

const LOCKFILES = new Set([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'pnpm-lock.yaml',
  'yarn.lock',
  'bun.lockb',
  'bun.lock',
  'cargo.lock',
  'poetry.lock',
  'pipfile.lock',
  'uv.lock',
  'gemfile.lock',
  'composer.lock',
  'go.sum',
  'flake.lock',
  'podfile.lock',
  'packages.lock.json',
  'mix.lock',
  'pubspec.lock',
]);

const DEPS_MANIFESTS = new Set([
  'package.json',
  'pyproject.toml',
  'pipfile',
  'setup.py',
  'setup.cfg',
  'cargo.toml',
  'go.mod',
  'gemfile',
  'composer.json',
  'pom.xml',
  'build.gradle',
  'build.gradle.kts',
  'mix.exs',
  'pubspec.yaml',
  'podfile',
]);

const GENERATED_PATH = [
  /(^|\/)(dist|__generated__|generated)\//,
  /\.pb\.(go|ts|js)$/,
  /_pb2(_grpc)?\.pyi?$/,
  /_pb\.(js|ts|d\.ts)$/,
  /\.min\.(js|css)$/,
  /\.generated\.[^/]+$/,
  /\.g\.dart$/,
  /\.map$/,
];

const GENERATED_MARKER =
  /@generated\b|DO NOT EDIT|Code generated by|auto-?generated|automatically generated/i;

const TEST_PATH = [
  /(^|\/)(__tests__|__test__|tests?|e2e)\//,
  /\.(test|spec)\.[^/]+$/,
  /(^|\/)test_[^/]+\.py$/,
  /_test\.(py|go|rb|rs|exs)$/,
  /_spec\.rb$/,
  /(Test|Tests|IT)\.(java|kt|cs|scala)$/,
];

const DOC_EXT = /\.(md|mdx|rst|adoc|txt)$/i;
const DOC_BASENAME = /^(license|copying|changelog|authors|contributing|notice|codeowners)/i;
const CONFIG_EXT = /\.(json|jsonc|ya?ml|toml|ini|cfg|conf|properties)$/i;
const CONFIG_BASENAME =
  /^(\.env.*|\.editorconfig|\.gitignore|\.gitattributes|\.npmrc|\.nvmrc|\..*rc(\..+)?|.*\.config\.[cm]?[jt]s|tsconfig.*\.json|dockerfile.*|docker-compose.*|makefile)$/i;

export function isTestPath(path: string): boolean {
  return TEST_PATH.some((re) => re.test(path));
}

export function isGeneratedPath(path: string): boolean {
  return GENERATED_PATH.some((re) => re.test(path));
}

/** Path-only classification. Cheap; content checks live in classifyFile / classifyHunk. */
export function classifyPath(path: string): Tag[] {
  const tags: Tag[] = [];
  const base = (path.split('/').pop() ?? path).toLowerCase();

  const lock = LOCKFILES.has(base) || /\.lock$/.test(base);
  const snapshot = /(^|\/)__snapshots__\//.test(path) || /\.snap$/.test(base);
  const vendor = /(^|\/)(vendor|node_modules|third_party|third-party|Pods)\//.test(path);
  const generated = isGeneratedPath(path);
  const test = isTestPath(path);
  const ci =
    /(^|\/)\.github\/(workflows|actions)\//.test(path) ||
    /(^|\/)\.circleci\//.test(path) ||
    /(^|\/)(\.gitlab-ci\.ya?ml|jenkinsfile|azure-pipelines\.ya?ml|\.travis\.ya?ml)$/i.test(path);

  if (lock) tags.push('lockfile');
  if (generated) tags.push('generated');
  if (snapshot) tags.push('snapshot');
  if (vendor) tags.push('vendor');
  if (test) tags.push('test');
  if (ci) tags.push('ci');
  if (/(^|\/)(migrations?|migrate)\//i.test(path) || /(^|\/)alembic\/versions\//.test(path)) {
    tags.push('migration');
  }
  const deps = !lock && (DEPS_MANIFESTS.has(base) || /^requirements.*\.txt$/.test(base));
  if (deps) tags.push('deps');
  const docs = DOC_EXT.test(base) || DOC_BASENAME.test(base) || /(^|\/)docs?\//i.test(path);
  if (docs && !deps && !test && !vendor && !generated) tags.push('docs');
  const config = CONFIG_EXT.test(base) || CONFIG_BASENAME.test(base);
  if (config && !lock && !snapshot && !vendor && !generated && !test && !docs) tags.push('config');
  return tags;
}

/** True when a hunk near the top of the file carries a generated-code marker. */
export function hasGeneratedMarker(file: ParsedFile): boolean {
  for (const h of file.hunks) {
    if (h.newStart > 15) continue;
    const head = h.lines.filter((l) => l.type !== 'del').slice(0, 15);
    if (head.some((l) => GENERATED_MARKER.test(l.content))) return true;
  }
  return false;
}
